namespace liquid::formats::apk {

result<std::vector<std::byte>> write(const package_metadata& metadata,
                                     const projection_options& options,
                                     std::span<const std::string> dependencies,
                                     std::span<const package::file> files,
                                     const generated_maintainer_scripts* scripts) {
    auto data_tar = package::tar(files, options.source_date_epoch, "usr");
    if (!data_tar) {
        return std::unexpected(data_tar.error());
    }
    auto data = deflate::gzip(*data_tar);
    auto data_digest = package::sha256(data);
    if (!data_digest) {
        return std::unexpected(data_digest.error());
    }
    auto installed_size = std::uint64_t{};
    for (const auto& file : files) {
        installed_size += file.bytes.size();
    }
    auto pkginfo = std::string{"# Generated by liquid\npkgname = "} + metadata.name +
                   "\npkgver = " + metadata.version + "-r" + metadata.release +
                   "\npkgdesc = " + metadata.description + "\nurl = " + metadata.homepage +
                   "\nbuilddate = " + std::to_string(options.source_date_epoch) +
                   "\nsize = " + std::to_string(installed_size) +
                   "\narch = " + metadata.architecture + "\nlicense = " + metadata.licence +
                   "\norigin = " + metadata.name + "\nmaintainer = " + metadata.maintainer +
                   "\ndatahash = " + package::hex_bytes(data_digest->bytes) + "\n";
    for (const auto& dependency : dependencies) {
        pkginfo += "depend = " + dependency + "\n";
    }
    for (const auto& provide : metadata.provides) {
        pkginfo += "provides = " + provide + "\n";
    }
    for (const auto& replace : metadata.replaces) {
        pkginfo += "replaces = " + replace + "\n";
    }
    auto control_files =
        std::vector<package::file>{{".PKGINFO", package::text_bytes(pkginfo), 0644}};
    if (scripts) {
        control_files.push_back({".pre-install", package::text_bytes(scripts->pre_install), 0755});
        control_files.push_back(
            {".post-install", package::text_bytes(scripts->post_install), 0755});
        control_files.push_back({".pre-deinstall", package::text_bytes(scripts->pre_remove), 0755});
        control_files.push_back(
            {".post-deinstall", package::text_bytes(scripts->post_remove), 0755});
    }
    auto control_tar = package::tar(control_files, options.source_date_epoch);
    if (!control_tar) {
        return std::unexpected(control_tar.error());
    }
    auto control = deflate::gzip(*control_tar);
    control.insert(control.end(), data.begin(), data.end());
    return control;
}

result<archive> read(std::span<const std::byte> bytes, std::uint64_t maximum_output) {
    auto control_member = deflate::gunzip(bytes, maximum_output);
    if (!control_member) {
        return std::unexpected(control_member.error());
    }
    if (control_member->second >= bytes.size()) {
        return std::unexpected(error{errc::corrupt, "apk data member is absent", "apk"});
    }
    auto data_member = deflate::gunzip(bytes.subspan(control_member->second),
                                       maximum_output - control_member->first.size());
    if (!data_member || control_member->second + data_member->second != bytes.size()) {
        return std::unexpected(data_member ? error{errc::corrupt, "apk has trailing bytes", "apk"}
                                           : data_member.error());
    }
    auto& registry = format_registry::global();
    auto control_tree = registry.unpack(control_member->first, "control.tar");
    auto data_tree = registry.unpack(data_member->first, "data.tar");
    if (!control_tree || !data_tree) {
        return std::unexpected(control_tree ? data_tree.error() : control_tree.error());
    }
    const auto info = std::ranges::find(control_tree->entries, ".PKGINFO", &format_entry::path);
    if (info == control_tree->entries.end()) {
        return std::unexpected(error{errc::corrupt, "apk PKGINFO is absent", "apk"});
    }
    auto output = archive{};
    output.pkginfo.assign(reinterpret_cast<const char*>(info->bytes.data()), info->bytes.size());
    auto scripts = generated_maintainer_scripts{};
    auto found_scripts = false;
    for (const auto& entry : control_tree->entries) {
        auto* destination = entry.path == ".pre-install"      ? &scripts.pre_install
                            : entry.path == ".post-install"   ? &scripts.post_install
                            : entry.path == ".pre-deinstall"  ? &scripts.pre_remove
                            : entry.path == ".post-deinstall" ? &scripts.post_remove
                                                              : nullptr;
        if (destination) {
            destination->assign(reinterpret_cast<const char*>(entry.bytes.data()),
                                entry.bytes.size());
            found_scripts = true;
        }
    }
    if (found_scripts) {
        output.scripts = std::move(scripts);
    }
    for (const auto& entry : data_tree->entries) {
        output.files.push_back(entry.path);
        if (entry.kind != format_entry_kind::member) {
            continue;
        }
        auto mode_text = package::attribute(entry.attributes, "mode");
        if (!mode_text) {
            return std::unexpected(mode_text.error());
        }
        auto mode = std::uint32_t{};
        const auto [end, code] =
            std::from_chars(mode_text->data(), mode_text->data() + mode_text->size(), mode);
        if (code != std::errc{} || end != mode_text->data() + mode_text->size()) {
            return std::unexpected(error{errc::corrupt, "apk file mode is invalid", entry.path});
        }
        output.payload.push_back({entry.path, entry.bytes, mode});
    }
    return output;
}

} // namespace liquid::formats::apk
